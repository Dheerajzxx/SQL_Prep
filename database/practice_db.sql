SET client_min_messages = warning;   -- hides harmless 'does not exist' notices on first run
DROP TABLE IF EXISTS logins, order_items, orders, products, customers, employees, departments CASCADE;

CREATE TABLE departments (
    dept_id     INT PRIMARY KEY,
    dept_name   TEXT NOT NULL,
    location    TEXT NOT NULL
);

CREATE TABLE employees (
    emp_id      INT PRIMARY KEY,
    emp_name    TEXT NOT NULL,
    dept_id     INT REFERENCES departments(dept_id),
    manager_id  INT REFERENCES employees(emp_id),   -- NULL for the CEO
    salary      NUMERIC(10,2) NOT NULL,
    hire_date   DATE NOT NULL,
    job_title   TEXT NOT NULL
);

CREATE TABLE customers (
    customer_id   INT PRIMARY KEY,
    customer_name TEXT NOT NULL,
    email         TEXT NOT NULL,                    -- NOT unique on purpose (duplicates exist)
    city          TEXT NOT NULL,
    signup_date   DATE NOT NULL
);

CREATE TABLE products (
    product_id    INT PRIMARY KEY,
    product_name  TEXT NOT NULL,
    category      TEXT NOT NULL,
    price         NUMERIC(8,2) NOT NULL
);

CREATE TABLE orders (
    order_id      INT PRIMARY KEY,
    customer_id   INT NOT NULL REFERENCES customers(customer_id),
    order_date    DATE NOT NULL,
    status        TEXT NOT NULL CHECK (status IN ('completed','cancelled','pending'))
);

CREATE TABLE order_items (
    order_item_id INT PRIMARY KEY,
    order_id      INT NOT NULL REFERENCES orders(order_id),
    product_id    INT NOT NULL REFERENCES products(product_id),
    quantity      INT NOT NULL,
    unit_price    NUMERIC(8,2) NOT NULL             -- price actually paid (can be discounted)
);

CREATE TABLE logins (                                -- one row per login event (a user can log in twice a day)
    login_id      SERIAL PRIMARY KEY,
    customer_id   INT NOT NULL REFERENCES customers(customer_id),
    login_date    DATE NOT NULL
);



